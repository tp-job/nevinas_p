/**
 * build-remixicon-subset.mjs
 *
 * Generates src/styles/vendor/remixicon-subset.css from the installed
 * `remixicon` package, containing ONLY the icon classes this project actually
 * uses.
 *
 * WHY: remixicon.css declares ~3,245 rules for ~2,800 icons and weighs 157 kB.
 * It is imported from index.css, which is a RENDER-BLOCKING stylesheet — so
 * every visitor paid ~21 kB gzip of critical-path CSS to get the ~125 icons the
 * site renders. This subset cuts that to a few hundred bytes.
 *
 * It also narrows @font-face to woff2 only. The upstream rule lists eot/ttf/
 * woff/svg fallbacks for IE6–iOS 4, which Vite dutifully copies into dist —
 * over 4.5 MB of assets (including a 3 MB .svg) that no supported browser will
 * ever request.
 *
 * REGENERATE after adding or removing `ri-*` icons:
 *     npm run icons:subset
 *
 * The generated file is committed so a plain `vite build` needs no extra step.
 */
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs'
import { join, dirname, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(root, 'src')
const UPSTREAM = join(root, 'node_modules/remixicon/fonts/remixicon.css')
const OUT_DIR = join(root, 'src/styles/vendor')
const OUT = join(OUT_DIR, 'remixicon-subset.css')

// Sizing/utility helpers are tiny and may be applied dynamically, so always keep
// them rather than trying to prove each one is referenced.
const ALWAYS_KEEP = new Set([
  'lg', 'xl', 'xxs', 'xs', 'sm',
  '1x', '2x', '3x', '4x', '5x', '6x', '7x', '8x', '9x', '10x',
  'fw',
])

const SCAN_EXT = new Set(['.tsx', '.ts', '.jsx', '.js', '.css', '.html'])

/** Recursively collect every source file worth scanning for icon names. */
function collectFiles(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    if (entry === 'node_modules' || entry === 'vendor') continue
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) out.push(...collectFiles(full))
    else if (SCAN_EXT.has(extname(entry))) out.push(full)
  }
  return out
}

const used = new Set(ALWAYS_KEEP)
for (const file of [...collectFiles(SRC), join(root, 'index.html')]) {
  const text = readFileSync(file, 'utf8')
  for (const m of text.matchAll(/\bri-([a-z0-9]+(?:-[a-z0-9]+)*)\b/g)) used.add(m[1])
}

const upstream = readFileSync(UPSTREAM, 'utf8')

// Pull the `content:` rule for each used icon straight from upstream so the
// codepoints can never drift out of sync with the shipped font file.
const kept = []
const missing = []
for (const name of [...used].sort()) {
  const rule = upstream.match(
    new RegExp(`^\\.ri-${name.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*(:before)?\\s*\\{[^}]*\\}`, 'm'),
  )
  if (rule) kept.push(rule[0])
  else missing.push(name)
}

const css = `/* AUTO-GENERATED by scripts/build-remixicon-subset.mjs — DO NOT EDIT.
 * Regenerate with: npm run icons:subset
 *
 * Subset of Remix Icon containing only the ${kept.length} classes this project
 * uses, instead of the full 157 kB / ~3,245-rule upstream stylesheet.
 * Remix Icon is released under the Remix Icon License 1.0 — https://remixicon.com
 */
@font-face {
  font-family: "remixicon";
  /* woff2 only — supported by every browser this project targets. The upstream
     eot/ttf/woff/svg fallbacks added >4.5 MB of never-requested assets to dist. */
  src: url("../../../node_modules/remixicon/fonts/remixicon.woff2") format("woff2");
  font-display: swap;
  font-style: normal;
  font-weight: normal;
}

[class^="ri-"], [class*=" ri-"] {
  font-family: "remixicon" !important;
  font-style: normal;
  -webkit-font-smoothing: antialiased;
  -moz-osx-font-smoothing: grayscale;
}

${kept.join('\n')}
`

mkdirSync(OUT_DIR, { recursive: true })
writeFileSync(OUT, css, 'utf8')

const before = Buffer.byteLength(upstream)
const after = Buffer.byteLength(css)
console.log(
  `remixicon subset: ${kept.length} rules kept — ` +
  `${(before / 1024).toFixed(1)} kB -> ${(after / 1024).toFixed(1)} kB ` +
  `(${(100 - (after / before) * 100).toFixed(1)}% smaller)`,
)
if (missing.length) {
  console.warn(
    `\n  WARNING: ${missing.length} ri-* token(s) found in source but absent from ` +
    `remixicon.css — likely dynamic names or typos, verify they render:\n  ${missing.join(', ')}`,
  )
}
